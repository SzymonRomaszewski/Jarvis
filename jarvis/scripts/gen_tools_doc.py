#!/usr/bin/env python3
"""Generate docs/tools.md from the tool registry in jarvis.py, so the reference can never go stale.

Usage:  python scripts/gen_tools_doc.py          (rewrites docs/tools.md)
        python scripts/gen_tools_doc.py --check  (exit 1 if docs/tools.md is out of date; used by the tests)
"""
import importlib.util
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "docs", "tools.md")


def load():
    os.environ["HOME"] = tempfile.mkdtemp()
    for key in list(os.environ):
        if key.startswith("JARVIS_") or key.endswith("_API_KEY"):
            del os.environ[key]
    spec = importlib.util.spec_from_file_location("jarvis_docgen", os.path.join(ROOT, "jarvis.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build() -> str:
    j = load()
    group_of = {name: group for group, (members, _) in j.TOOL_GROUPS.items() for name in members}
    rows = []
    for name, description, schema, _ in j.TOOLS:
        args = ", ".join(f"`{k}`" + ("" if k in schema["required"] else "?") for k in schema["properties"]) or "none"
        notes = []
        if name == "run_shell":
            notes.append("asks you to confirm, by voice")
        if name == "run_applescript":
            notes.append("asks you to confirm when the script looks risky")
        if name in j.SENSITIVE_TOOLS:
            notes.append("blocked for the rest of a request once web or screen content has been read")
        if name in j.UNTRUSTED_TOOLS:
            notes.append("its output is treated as untrusted")
        rows.append(f"| `{name}` | {group_of.get(name, 'always')} | {description} | {args} | {'; '.join(notes) or '-'} |")
    groups = "\n".join(f"- **{g}**" for g in j.TOOL_GROUPS)
    return f"""# Tool reference

> Generated by `scripts/gen_tools_doc.py` from the registry in `jarvis.py`. Do not edit by hand.

Jarvis's AI brain acts on your Mac by calling these tools. `?` marks an optional argument.

To keep requests small (and free plans going further), the AI is only sent a **group** of tools when your request,
or the last few things you said, mention something related to it. Tools marked `always` are sent every time.
The groups are:

{groups}

| Tool | Sent | What it does | Arguments | Safety |
|---|---|---|---|---|
{chr(10).join(rows)}

## Safety rules that apply to tools

- `run_shell` and risky `run_applescript` calls always need a spoken (or typed) yes.
- After the AI has read anything from the web (`web_search`) or your screen (`look_at_screen`), the tools that can act on your
  Mac (`run_shell`, `run_applescript`, `type_text`) are switched off until your next request. Text planted on a web page
  can't make Jarvis do anything harmful.
- Voice shortcuts and instant commands run without the AI, so they are unaffected by any of this.
"""


def main():
    text = build()
    if "--check" in sys.argv:
        current = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if current != text:
            print("docs/tools.md is out of date. Run: python scripts/gen_tools_doc.py")
            return 1
        print("docs/tools.md is up to date")
        return 0
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
